/* ---------- せいちょう曲線 ---------- */
function expForLevel(level, growth) {
  if (level <= 1) return 0;
  const n = level;
  switch (growth) {
    case 'fast':       return Math.floor(4 * n * n * n / 5);
    case 'mediumSlow': return Math.floor(6 * n * n * n / 5 - 15 * n * n + 100 * n - 140);
    case 'slow':       return Math.floor(5 * n * n * n / 4);
    default:           return Math.floor(n * n * n);
  }
}
function expToNext(level, growth) {
  if (level >= 100) return Infinity;
  return Math.max(1, expForLevel(level + 1, growth) - expForLevel(level, growth));
}
function evYield(sp) {
  const entries = Object.entries(sp.base).filter(([k]) => k !== 'hp').sort((a, b) => b[1] - a[1]);
  const stat = entries[0][0];
  return { [stat]: sp.evolve ? 1 : 2 };
}

